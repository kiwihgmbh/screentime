-- --------------------------------------------------------- weekly checks

-- A check keeps the budget it was computed against, so the history stays
-- readable even if somebody later edits the past.
alter table weekly_checks add column budget_minutes integer;
alter table weekly_checks add column tolerance_minutes integer;
alter table weekly_checks add column settings_scope varchar(8);

-- checks made so far were all made against the one set there was
update weekly_checks c
set budget_minutes    = (select value::integer from settings_v1 where key = 'weeklyMinutes')
                        + case when coalesce(f.bonus_active, false)
                               then (select value::integer from settings_v1 where key = 'bonusMinutes')
                               else 0 end,
    tolerance_minutes = (select value::integer from settings_v1 where key = 'toleranceMinutes'),
    settings_scope    = 'TERM'
from (select c2.id, wf.bonus_active
      from weekly_checks c2
      left join week_flags wf on wf.week_start = c2.week_start) f
where f.id = c.id;

alter table weekly_checks alter column budget_minutes set not null;
alter table weekly_checks alter column tolerance_minutes set not null;
alter table weekly_checks alter column settings_scope set not null;
alter table weekly_checks add constraint ck_weekly_checks_scope check (settings_scope in ('TERM', 'HOLIDAY'));

drop table settings_v1;
